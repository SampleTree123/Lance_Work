import hashlib
import itertools
import json
import math
from pathlib import Path
import random
import time

AXES = ('identity', 'action', 'camera', 'aspect', 'site', 'hair_color')
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]


def read(path):
    return json.loads(Path(path).read_text(encoding='utf-8-sig'))


def write(path, value):
    Path(path).write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')


def digest(value, prefix='simn'):
    return prefix + '_' + hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()[:20]


def distribution(values):
    vals = sorted(values)
    if not vals:
        return {'count': 0, 'mean': 0, 'p95': 0, 'max': 0, 'gini': 0}
    n, total = len(vals), sum(vals)
    return {'count': n, 'mean': total / n, 'p95': vals[math.ceil(.95*n)-1],
            'max': vals[-1], 'gini': (2*sum((i+1)*x for i,x in enumerate(vals))/(n*total)-(n+1)/n) if total else 0,
            'zeros': vals.count(0), 'sum': total}


class Catalog:
    def __init__(self, inventory, checkpoint, appearance=None, split_policy='identity'):
        self.inventory = inventory
        self.split_policy=split_policy
        self.checkpoint = checkpoint
        self.people = inventory['identities']
        self.sex = {r['id']: r['sex'] for r in self.people}
        self.action_sexes = inventory.get('action_sexes', {})
        self.axes = {k: inventory[k] for k in ('actions', 'cameras', 'aspects', 'hair_colors')}
        self.axes['sites'] = [r['id'] for r in checkpoint['sites']]
        self.excluded = {(s['id'], e['action_id'], e['camera_id'], e['aspect'])
                         for s in checkpoint['sites'] for e in s.get('manual_exclusions', [])
                         if e.get('decision') == 'excluded'}
        self.rejects = Counter()
        self.appearance=appearance
        self.outfits={}
        self.hairs={}
        self.garment_manifest={}
        if appearance:
            for sex,rows in appearance['presets_by_sex'].items():
                candidates=[]
                for r in rows:
                    if r.get('hair_deny'): continue
                    choice=r['choice']
                    family=next(f for f in appearance['families_by_sex'][sex] if f['family_id'] == choice['family_id'])
                    if not family.get('hair_interface',{}).get('allow_all'): continue
                    group=next(g for g in family['groups'] if g['group_id'] == choice['group_id'])
                    for slot,options in group['slot_options'].items():
                        if slot == 'shoes' or slot not in choice['slot_choices']: continue
                        options=[o for o in options if not (o.get('hair_interface') or {}).get('deny_all')]
                        if len(options)>1: candidates.append((len(options),family['family_id'],group['group_id'],slot,choice,options))
                _,family,group,slot,base,options=max(candidates,key=lambda x:(x[0],x[1],x[2],x[3]))
                self.outfits[sex]={o['asset_id']:{'hair_deny':False} for o in options}
                self.garment_manifest[sex]={'family_id':family,'group_id':group,'edited_slot':slot,
                                          'frozen_choice_except_edited_slot':{**base,'slot_choices':{k:v for k,v in base['slot_choices'].items() if k != slot}},
                                          'garment_options':[o['asset_id'] for o in options]}
                self.hairs[sex]=['none']+[r['hair_id'] for r in appearance['hairs_by_sex'][sex]]

    def valid(self, state):
        p, a, c, aspect, site, color = state[:6]
        if self.action_sexes.get(a) and self.sex[p] not in self.action_sexes[a]:
            self.rejects['action_sex'] += 1
            return False
        if (site, a, c, aspect) in self.excluded:
            self.rejects['saved_site_exclusion'] += 1
            return False
        if self.appearance:
            outfit,hair=state[6:]
            if self.outfits[self.sex[p]][outfit]['hair_deny'] and hair != 'none':
                self.rejects['outfit_forbids_hair']+=1
                return False
            if hair == 'none' and color != 'original':
                self.rejects['bald_color_invisible_noop']+=1
                return False
        return True

    def domains(self, split):
        result = {}
        for sex in ('female', 'male'):
            people = sorted(r['id'] for r in self.people if r['sex'] == sex)
            cut = max(1, round(len(people)*.8))
            selected = people if self.split_policy == 'scene' else (people[:cut] if split == 'train' else people[cut:])
            acts = [a for a in self.axes['actions'] if not self.action_sexes.get(a) or sex in self.action_sexes[a]]
            sites=self.axes['sites']
            if self.split_policy == 'scene': sites=sites[:16] if split == 'train' else sites[16:]
            result[sex] = [selected, acts, self.axes['cameras'], self.axes['aspects'], sites, self.axes['hair_colors']]
            if self.appearance:
                result[sex]+=[list(self.outfits[sex]),self.hairs[sex]]
        return result


def build_graph(cat, route, split, budget, rng, cover_values=False):
    """Grow legal edge endpoints, then register all induced atomic edges."""
    domains = cat.domains(split)
    nodes, known, parent, cell, generation = [], {}, [], [], []
    bysex = defaultdict(list)
    def add(state, ancestor=None, axis=None, cellid=None):
        if state in known or not cat.valid(state):
            return None
        i = len(nodes)
        known[state] = i
        nodes.append(state)
        parent.append(ancestor)
        cell.append(cellid)
        bysex[cat.sex[state[0]]].append(i)
        generation.append({'node':i, 'parent':ancestor, 'axis':axis})
        return i
    for sex, options in domains.items():
        # Deterministic root only. Every other node must have an edit parent.
        root = list(v[0] for v in options)
        found = False
        for site in options[4]:
            root[4] = site
            if cat.valid(tuple(root)):
                add(tuple(root), cellid=sex+'_0')
                found = True
                break
        if not found:
            raise ValueError('No legal deterministic root for '+sex)
    latest = {s: bysex[s][-1] for s in bysex}
    if cover_values:
        # Real coverage targets are reached only by editing an existing endpoint.
        for sex,options in domains.items():
            for axis,values in enumerate(options):
                for value in values:
                    if any(nodes[i][axis] == value for i in bysex[sex]): continue
                    candidates=[latest[sex]]+bysex[sex]
                    for source in candidates:
                        state=list(nodes[source])
                        state[axis]=value
                        made=add(tuple(state),source,axis,sex+'_coverage')
                        if made is not None:
                            latest[sex]=made
                            break
                    else:
                        raise ValueError(f'Cannot cover {sex}/{AXES[axis]}/{value}')
    cell_specs, active_cell = {}, {}
    for sex, ids in bysex.items():
        active_cell[sex] = 0
        cell_specs[(sex, 0)] = (ids[0], {a:rng.sample(v, min(3,len(v))) for a,v in enumerate(domains[sex])})
    attempts = 0
    while len(nodes) < budget and attempts < budget*300:
        attempts += 1
        sex = min(bysex, key=lambda s:len(bysex[s]))
        options = domains[sex]
        dense = route == 'dense_neighborhoods' or (route == 'hybrid' and len(nodes) >= budget*.6)
        if dense:
            cid = active_cell[sex]
            rootidx, local = cell_specs[(sex,cid)]
            members = [i for i in bysex[sex] if cell[i] == sex+'_'+str(cid)]
            if len(members) >= 72 or attempts % 240 == 0:
                cid += 1
                active_cell[sex] = cid
                # A cell is attached by edits from an existing scaffold state.
                rootidx = rng.choice(bysex[sex])
                local = {a:list(dict.fromkeys([nodes[rootidx][a]]+rng.sample(v,min(2,len(v))))) for a,v in enumerate(options)}
                cell_specs[(sex,cid)] = (rootidx, local)
                members = []
            source = rng.choice(members or [rootidx])
            axis = rng.randrange(len(AXES))
            value = rng.choice(local[axis])
            cellid = sex+'_'+str(cid)
        else:
            # Chain-first: 2--5 edit episodes; latest state grows a sparse scaffold.
            source = latest[sex] if rng.random() < .88 else rng.choice(bysex[sex])
            axis = rng.randrange(len(AXES))
            value = rng.choice(options[axis])
            cellid = sex+'_scaffold'
        state = list(nodes[source])
        state[axis] = value
        made = add(tuple(state),source,axis,cellid)
        if made is not None:
            latest[sex] = made
    if len(nodes) != budget:
        raise RuntimeError(f'{route}/{split}: only {len(nodes)} of {budget} nodes')
    buckets = defaultdict(list)
    for i, node in enumerate(nodes):
        for axis in range(len(AXES)):
            buckets[(axis,node[:axis]+node[axis+1:])].append(i)
    adj = [[] for _ in nodes]
    edges = {}
    for (axis, _), ids in buckets.items():
        for u in ids:
            for v in ids:
                if u != v and cat.sex[nodes[u][0]] == cat.sex[nodes[v][0]]:
                    edges[(u,v)] = axis
                    adj[u].append((v,axis))
    for rows in adj:
        rows.sort()
    assert all(adj)
    assert len(known) == len(nodes)
    assert all(sum(a != b for a,b in zip(nodes[g['parent']],nodes[g['node']])) == 1
               for g in generation if g['parent'] is not None)
    return nodes,adj,edges,generation,attempts


def quotas(total, followup=True, branch_min_length=None, fork_length_policy='equal'):
    assert total % 3 == 0
    result=[]
    minimum=branch_min_length or (3 if followup else 2)
    for branch,n,lengths in ((False,total*2//3,[2,3,4,5]),(True,total//3,list(range(minimum,6)))):
        if branch and fork_length_policy == '20_40_40':
            assert minimum == 3 and n % 5 == 0
            result.extend((k,True,n*w//5) for k,w in ((3,1),(4,2),(5,2)))
            continue
        q,r=divmod(n,len(lengths))
        result.extend((k,branch,q+(i<r)) for i,k in enumerate(lengths))
    return result


def sample_sessions(nodes, adj, edges, total, rng, balanced=True, followup=True, branch_min_length=None, allow_source_alias=False, quality=False, fork_length_policy='equal', source_balanced=False):
    node_refs,edge_refs=Counter(),Counter()
    node_sessions,edge_sessions=Counter(),Counter()
    sessions,signatures=[],set()
    counts=Counter()
    retries=0
    starts=list(range(len(nodes)))
    rng.shuffle(starts)
    targets=[]
    for k,b,n in quotas(total,followup,branch_min_length,fork_length_policy):
        # With fork L3/4/5=20/40/40, root-only L3 plus 25% of longer
        # forks gives exactly root40% / historical-intermediate60%.
        root_count=n if k == 3 else n//4
        targets.extend((k,b,source_balanced and b and i >= root_count) for i in range(n))
    branch_starts=[i for i,rows in enumerate(adj) if len({a for v,a in rows}) >= 2]
    two_axis_paths=[(u,v,w,a,b) for u,rows in enumerate(adj) for v,a in rows for w,b in adj[v] if a != b] if quality else []
    two_axis_capacity=len(two_axis_paths)
    rng.shuffle(targets)
    for k,branch,nonroot_source in targets:
        succeeded=False
        for attempt in range(1000):
            retries+=1
            if len(sessions) < len(starts) and not quality:
                start=starts[len(sessions)]
            elif balanced:
                pool=branch_starts if quality and branch else range(len(nodes))
                start=(rng.choice(pool) if source_balanced and rng.random() < .25 else
                       min(rng.sample(pool,min(12,len(pool))),key=lambda i:node_refs[i]))
            else:
                start=rng.randrange(len(nodes))
            occ=[start]
            parents=[None]
            axes=[]
            branch_turn=rng.randint(3 if nonroot_source else 2,k-1 if followup else k) if branch else None
            ok=True
            preselected=quality and k == 2 and not branch
            if preselected:
                if not two_axis_paths:
                    ok=False
                else:
                    idx=min(rng.sample(range(len(two_axis_paths)),min(16,len(two_axis_paths))),
                            key=lambda j:sum(node_refs[n] for n in two_axis_paths[j][:3]))
                    u,v,w,a,b=two_axis_paths[idx]
                    two_axis_paths[idx]=two_axis_paths[-1]
                    two_axis_paths.pop()
                    occ,parents,axes=[u,v,w],[None,0,1],[a,b]
            for turn in (() if preselected else range(1,k+1)):
                if turn == branch_turn:
                    history=[p for p in range(turn-1) if occ[p] != occ[-1]
                             and (allow_source_alias or occ[:turn].count(occ[p]) == 1)]
                    if source_balanced:
                        history=[p for p in history if (p > 0 if nonroot_source else p == 0)]
                    if not history:
                        ok=False
                        break
                    source_occ=rng.choice(history)
                else:
                    source_occ=turn-1
                source=occ[source_occ]
                choices=adj[source]
                if quality:
                    choices=[(v,a) for v,a in choices if v not in occ]
                    if turn == branch_turn:
                        differences=[i for i,(x,y) in enumerate(zip(nodes[source],nodes[occ[-1]])) if x != y]
                        choices=[(v,a) for v,a in choices if any(d != a for d in differences)]
                    if not choices:
                        ok=False
                        break
                if balanced and not (source_balanced and rng.random() < .2):
                    picked=min(rng.sample(choices,min(8,len(choices))),key=lambda x:(edge_refs[(source,x[0])],node_refs[x[0]],rng.random()))
                else:
                    picked=rng.choice(choices)
                target,axis=picked
                occ.append(target)
                parents.append(source_occ)
                axes.append(axis)
            if not ok:
                continue
            if quality and len(set(axes)) < 2:
                continue
            sig=(tuple(occ),tuple(parents))
            if sig in signatures:
                continue
            signatures.add(sig)
            sessions.append((occ,parents,axes))
            node_refs.update(occ)
            node_sessions.update(set(occ))
            edge_sessions.update({(occ[parents[t]],occ[t]) for t in range(1,k+1)})
            for t in range(1,k+1):
                edge_refs[(occ[parents[t]],occ[t])]+=1
                assert edges[(occ[parents[t]],occ[t])] == axes[t-1]
                if sum(x == occ[parents[t]] for x in occ[:t]) > 1:
                    counts['source_occurrence_alias_turns']+=1
            counts['length_'+str(k)]+=1
            counts['branch' if branch else 'straight']+=1
            counts['repeat_node_sessions']+=len(set(occ)) < len(occ)
            ancestor_loop=False
            for t in range(1,k+1):
                p=parents[t]
                while p is not None:
                    if occ[p] == occ[t]: ancestor_loop=True
                    p=parents[p]
            counts['ancestor_state_loop_sessions']+=ancestor_loop
            counts['returns_to_root_sessions']+=occ[-1] == occ[0]
            if branch:
                counts['branch_source_alias_sessions']+=occ[:branch_turn].count(occ[parents[branch_turn]]) > 1
                counts['branch_turn_'+str(branch_turn)]+=1
                counts['branch_source_depth_'+str(parents[branch_turn])]+=1
                counts['branch_source_lag_'+str(branch_turn-1-parents[branch_turn])]+=1
                counts['branch_then_followup_sessions']+=branch_turn < k
            succeeded=True
            break
        if not succeeded:
            counts['unfilled_'+str((k,branch))]+=1
    metrics={'requested':total,'sampled_unique_sessions':len(sessions),'unique_session_lower_bound':len(signatures),
             'capacity_claim':'lower_bound_only_not_exhaustive_capacity','sampling_attempts':retries,
             'node_occurrence_reuse':distribution([node_refs[i] for i in range(len(nodes))]),
             'node_distinct_session_reuse':distribution([node_sessions[i] for i in range(len(nodes))]),
             'directed_edge_reuse_including_zeros':distribution([edge_refs[e] for e in edges]),
             'used_directed_edge_reuse':distribution(list(edge_refs.values())),
             'edge_distinct_session_reuse_including_zeros':distribution([edge_sessions[e] for e in edges]),
             'unique_directed_edges_used':len(edge_refs),'edge_coverage_fraction':len(edge_refs)/len(edges),
             'counts':dict(sorted(counts.items()))}
    metrics['all_nodes_referenced']=node_refs.keys() == set(range(len(nodes)))
    metrics['quality_nonrepeated_state_sessions']=sum(len(set(o)) == len(o) for o,p,a in sessions)
    if quality: metrics['exact_available_two_axis_length2_straight_paths']=two_axis_capacity
    metrics['quality_at_least_two_axes_sessions']=sum(len(set(a)) >= 2 for o,p,a in sessions)
    if not quality:
        assert len(sessions) == total, metrics
        assert counts['straight'] == total*2//3 and counts['branch'] == total//3
        assert node_refs.keys() == set(range(len(nodes)))
    return sessions,metrics


def components(adj):
    unseen=set(range(len(adj)))
    sizes=[]
    while unseen:
        start=unseen.pop()
        stack=[start]
        size=1
        while stack:
            for j,_ in adj[stack.pop()]:
                if j in unseen:
                    unseen.remove(j)
                    stack.append(j)
                    size+=1
        sizes.append(size)
    return sorted(sizes,reverse=True)


def straight_walk_capacity(adj):
    # Exact finite graph walk counts, including returns and repeated edges.
    ways=[1]*len(adj)
    result={}
    for length in range(1,6):
        ways=[sum(ways[v] for v,_ in rows) for rows in adj]
        if length >= 2:
            result[str(length)]=sum(ways)
    return result


def serial_session(session,nodes,index):
    occ,parents,axes=session
    return {'session_id':digest(([digest(dict(zip(AXES,nodes[n]))) for n in occ],parents),'sims'),'edit_count':len(axes),
            'has_branch':any(p != t-1 for t,p in enumerate(parents) if t),
            'occurrences':[{'occurrence_id':f's{index}:o{t}','node_id':digest(dict(zip(AXES,nodes[n]))),
                            'parent_occurrence_id':None if t == 0 else f's{index}:o{parents[t]}',
                            'source_occurrence_index_gt':parents[t],
                            'edit_axis':None if t == 0 else AXES[axes[t-1]],
                            'state':dict(zip(AXES,nodes[n]))} for t,n in enumerate(occ)]}


def run(args):
    global AXES
    if args.appearance:
        AXES=AXES+('garment_slot','hair')
    inv=read(args.inventory)
    checkpoint=read(args.checkpoint)
    appearance=read(args.appearance) if args.appearance else None
    result={'schema':'offline_graph_routes_v1','kind':'catalog_constrained_synthetic_topology_NOT_UE_validation',
            'axes':AXES,'inventory_sha256':hashlib.sha256(args.inventory.read_bytes()).hexdigest(),
            'checkpoint_sha256':hashlib.sha256(args.checkpoint.read_bytes()).hexdigest(),
            'node_budget_includes':'all_roots_intermediates_outputs','split_policy':('candidate_unseen_identity_80_20_within_each_sex_not_frozen' if args.split_policy == 'identity' else 'candidate_unseen_scene_16_5_all_identities_not_frozen'),
            'followup_after_branch':not args.allow_last_branch,'branch_source_state_unique':not args.allow_source_alias,'runs':[]}
    result['fork_length_policy']=args.fork_length_policy
    result['source_balanced_sensitivity']=args.source_balanced
    result['quality_contract']=({'all_output_states_unique':True,'minimum_distinct_edit_axes':2,
                                 'fork_keeps_source_latest_difference_outside_edited_axis':True,
                                 'cover_all_split_axis_values_by_edit_growth':True} if args.quality else 'capacity_only_baseline_allows_state_revisits')
    if args.appearance:
        result['appearance_sha256']=hashlib.sha256(args.appearance.read_bytes()).hexdigest()
    for seed in args.seeds:
        for route in args.routes:
            for split,budget,total in (('train',args.train_nodes,args.train_sessions),('test',args.test_nodes,args.test_sessions)):
                tick=time.perf_counter()
                rng=random.Random(seed+(0 if split == 'train' else 10000))
                cat=Catalog(inv,checkpoint,appearance,args.split_policy)
                nodes,adj,edges,generation,attempts=build_graph(cat,route,split,budget,rng,cover_values=args.quality)
                sessions,metrics=sample_sessions(nodes,adj,edges,total,rng,followup=not args.allow_last_branch,branch_min_length=args.branch_min_length,allow_source_alias=args.allow_source_alias,quality=args.quality,fork_length_policy=args.fork_length_policy,source_balanced=args.source_balanced)
                coverage={axis:dict(Counter(n[i] for n in nodes)) for i,axis in enumerate(AXES)}
                uniform,uniform_metrics=sample_sessions(nodes,adj,edges,total,random.Random(seed+515),balanced=False,followup=not args.allow_last_branch,branch_min_length=args.branch_min_length,allow_source_alias=args.allow_source_alias,quality=args.quality,fork_length_policy=args.fork_length_policy,source_balanced=args.source_balanced)
                row={'seed':seed,'route':route,'split':split,'unique_nodes':len(nodes),'unique_directed_edges':len(edges),
                     'degree':distribution([len(v) for v in adj]),'connected_component_sizes':components(adj),
                     'exact_unique_straight_walk_capacity_by_length':straight_walk_capacity(adj),
                     'expansion_attempts':attempts,'rejected_candidates':dict(cat.rejects),'axis_edge_counts':dict(Counter(AXES[a] for a in edges.values())),
                     'node_axis_coverage':coverage,'balanced_sampler':metrics,'uniform_sampler':uniform_metrics,
                     'elapsed_seconds':round(time.perf_counter()-tick,3)}
                if appearance:
                    row['garment_manifest']=cat.garment_manifest
                # Compare exact directed state hashes across train/test later.
                row['node_hashes']=[digest(dict(zip(AXES,n))) for n in nodes]
                result['runs'].append(row)
                if seed == args.seeds[0] and not args.no_artifacts:
                    prefix=HERE/f'{args.artifact_tag}{route}_{split}'
                    write(str(prefix)+'_graph.json',{'kind':result['kind'],'axes':AXES,
                          'nodes':[{'node_id':digest(dict(zip(AXES,n))),'state':dict(zip(AXES,n)),
                                    'generation_parent_index':g['parent'],'generation_axis':None if g['axis'] is None else AXES[g['axis']]} for n,g in zip(nodes,generation)],
                          'edges':[{'source_index':u,'target_index':v,'axis':AXES[a]} for (u,v),a in edges.items()]})
                    with Path(str(prefix)+'_sessions.jsonl').open('w',encoding='utf-8') as f:
                        for i,s in enumerate(sessions):
                            occ,parents,axes=s
                            f.write(json.dumps({'session_id':digest(([row['node_hashes'][n] for n in occ],parents),'sims'),
                                                'node_indices':occ,'parent_occurrence_indices_gt':parents,
                                                'edge_axes':[AXES[a] for a in axes]},separators=(',',':'))+'\n')
                    examples=[]
                    wanted={'straight','branch','branch_followup','closed_loop','source_alias'}
                    for i,s in enumerate(sessions):
                        occ,parents,axes=s
                        branch=any(p != t-1 for t,p in enumerate(parents) if t)
                        labels=set()
                        if branch: labels.update(('branch','branch_followup'))
                        else: labels.add('straight')
                        if len(set(occ)) < len(occ): labels.add('closed_loop')
                        if any(sum(x == occ[parents[t]] for x in occ[:t]) > 1 for t in range(1,len(occ))): labels.add('source_alias')
                        if labels & wanted:
                            examples.append({'labels':sorted(labels),**serial_session(s,nodes,i)})
                            wanted-=labels
                        if not wanted: break
                    write(str(prefix)+'_examples.json',examples)
                print(json.dumps({k:row[k] for k in ('seed','route','split','unique_nodes','unique_directed_edges','elapsed_seconds')},ensure_ascii=False),flush=True)
    for seed in args.seeds:
        for route in args.routes:
            group=[r for r in result['runs'] if r['seed'] == seed and r['route'] == route]
            train,test=group
            assert not set(train['node_hashes']) & set(test['node_hashes'])
            for row in group:
                row.pop('node_hashes')
    write(args.output,result)


